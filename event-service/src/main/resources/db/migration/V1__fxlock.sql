CREATE TABLE fx_customer (id VARCHAR2(64) PRIMARY KEY);

CREATE TABLE fx_rate_snapshot (
 id VARCHAR2(36) PRIMARY KEY, pair VARCHAR2(7) NOT NULL,
 rate NUMBER(20,10) NOT NULL CHECK(rate>0), observed_at TIMESTAMP(6) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL, CONSTRAINT uq_rate_observation UNIQUE(pair,observed_at)
);

CREATE TABLE fx_quote (
 id VARCHAR2(36) PRIMARY KEY, owner_id VARCHAR2(64) NOT NULL REFERENCES fx_customer(id),
 snapshot_id VARCHAR2(36) NOT NULL REFERENCES fx_rate_snapshot(id),
 source_ccy VARCHAR2(3) NOT NULL, target_ccy VARCHAR2(3) NOT NULL,
 source_amount NUMBER(18,2) NOT NULL CHECK(source_amount>0), target_amount NUMBER(18,2) NOT NULL CHECK(target_amount>0),
 offered_rate NUMBER(20,10) NOT NULL CHECK(offered_rate>0), confidence NUMBER(5,2) NOT NULL CHECK(confidence BETWEEN 0 AND 100),
 created_at TIMESTAMP(6) NOT NULL, expires_at TIMESTAMP(6) NOT NULL,
 status VARCHAR2(10) DEFAULT 'OPEN' NOT NULL CHECK(status IN ('OPEN','SETTLED')),
 CHECK(source_ccy<>target_ccy), CHECK(expires_at>created_at)
);


CREATE TABLE fx_wallet (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id VARCHAR2(64) NOT NULL REFERENCES fx_customer(id),
 currency VARCHAR2(3) NOT NULL, opening_balance NUMBER(18,2) NOT NULL CHECK(opening_balance>=0),
 balance NUMBER(18,2) NOT NULL CHECK(balance>=0), CONSTRAINT uq_wallet UNIQUE(owner_id,currency)
);


CREATE TABLE fx_settlement (
 id VARCHAR2(36) PRIMARY KEY, quote_id VARCHAR2(36) NOT NULL REFERENCES fx_quote(id),
 owner_id VARCHAR2(64) NOT NULL REFERENCES fx_customer(id), source_amount NUMBER(18,2) NOT NULL,
 target_amount NUMBER(18,2) NOT NULL, completed_at TIMESTAMP(6) NOT NULL,
 CONSTRAINT uq_settlement_quote UNIQUE(quote_id)
);


CREATE TABLE fx_ledger (
 id VARCHAR2(36) PRIMARY KEY, settlement_id VARCHAR2(36) NOT NULL REFERENCES fx_settlement(id),
 wallet_id NUMBER NOT NULL REFERENCES fx_wallet(id), delta NUMBER(18,2) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL, CONSTRAINT uq_ledger_leg UNIQUE(settlement_id,wallet_id)
);


CREATE TABLE fx_idempotency (
 owner_id VARCHAR2(64) NOT NULL REFERENCES fx_customer(id), idem_key VARCHAR2(100) NOT NULL,
 quote_id VARCHAR2(36) NOT NULL REFERENCES fx_quote(id), settlement_id VARCHAR2(36) NOT NULL REFERENCES fx_settlement(id),
 CONSTRAINT pk_idempotency PRIMARY KEY(owner_id,idem_key)
);


CREATE TABLE fx_audit (
 id VARCHAR2(36) PRIMARY KEY, owner_id VARCHAR2(64), quote_id VARCHAR2(36),
 outcome VARCHAR2(20) NOT NULL, detail VARCHAR2(500) NOT NULL, created_at TIMESTAMP(6) NOT NULL
);


CREATE TABLE fx_outbox (
 id VARCHAR2(36) PRIMARY KEY, topic VARCHAR2(80) NOT NULL, aggregate_id VARCHAR2(64) NOT NULL,
 payload CLOB NOT NULL, status VARCHAR2(12) DEFAULT 'PENDING' NOT NULL,
 attempts NUMBER(10) DEFAULT 0 NOT NULL, available_at TIMESTAMP(6) NOT NULL,
 claim_token VARCHAR2(36), claimed_at TIMESTAMP(6), published_at TIMESTAMP(6),
 last_error VARCHAR2(500), created_at TIMESTAMP(6) NOT NULL,
 CHECK(status IN ('PENDING','INFLIGHT','PUBLISHED')),
 CHECK(topic IN ('fx-rate-updated','fx-settlement-completed','fx-system-alert'))
);


CREATE INDEX ix_outbox_pending ON fx_outbox(status,available_at);


CREATE TABLE fx_event_history (
 event_id VARCHAR2(36) PRIMARY KEY, event_type VARCHAR2(80) NOT NULL,
 aggregate_id VARCHAR2(64) NOT NULL, payload CLOB NOT NULL, received_at TIMESTAMP(6) NOT NULL
);


